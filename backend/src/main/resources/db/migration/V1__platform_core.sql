-- Platform ("control plane") tables: everything Tsukuyomi itself needs to know.
-- Tenant data never lives here; each project gets its own schema.

create table tsk_platform.account (
    id            uuid primary key default gen_random_uuid(),
    email         text not null unique,
    password_hash text not null,
    created_at    timestamptz not null default now()
);

-- Dashboard login sessions. The browser holds a random token in a cookie;
-- we store only its SHA-256, so a database leak does not expose usable sessions.
create table tsk_platform.session (
    token_hash text primary key,
    account_id uuid not null references tsk_platform.account (id) on delete cascade,
    expires_at timestamptz not null
);

create table tsk_platform.project (
    id              uuid primary key default gen_random_uuid(),
    account_id      uuid not null references tsk_platform.account (id) on delete cascade,
    name            text not null,
    -- Name of the Postgres schema holding this project's tables, e.g. p_3fa9c1d2e4b7.
    -- Generated by us, never taken from user input.
    schema_name     text not null unique check (schema_name ~ '^p_[0-9a-f]{12}$'),
    -- Signs this project's end-user tokens (used from M3).
    jwt_secret      bytea not null,
    -- Bumped by every schema migration.
    schema_version  integer not null default 0,
    created_at      timestamptz not null default now(),
    unique (account_id, name)
);

create table tsk_platform.api_key (
    id         uuid primary key default gen_random_uuid(),
    project_id uuid not null references tsk_platform.project (id) on delete cascade,
    kind       text not null check (kind in ('anon', 'service')),
    -- SHA-256 of the key. The key itself is shown once and never stored.
    key_hash   text not null unique,
    -- First characters of the key, so the owner can tell keys apart.
    prefix     text not null,
    created_at timestamptz not null default now(),
    unique (project_id, kind)
);

-- The catalog: our own record of every table and column users have designed.
-- The data API resolves names against this, never against request text.
create table tsk_platform.table_meta (
    id         uuid primary key default gen_random_uuid(),
    project_id uuid not null references tsk_platform.project (id) on delete cascade,
    name       text not null,
    unique (project_id, name)
);

create table tsk_platform.column_meta (
    id        uuid primary key default gen_random_uuid(),
    table_id  uuid not null references tsk_platform.table_meta (id) on delete cascade,
    name      text not null,
    type      text not null,
    nullable  boolean not null,
    is_unique boolean not null,
    -- System columns (id, created_at) are added to every table and cannot be changed.
    is_system boolean not null default false,
    position  integer not null,
    unique (table_id, name)
);

-- History of schema changes, one row per applied migration.
create table tsk_platform.migration (
    project_id uuid not null references tsk_platform.project (id) on delete cascade,
    version    integer not null,
    operations jsonb not null,
    sql        text not null,
    applied_at timestamptz not null default now(),
    primary key (project_id, version)
);
