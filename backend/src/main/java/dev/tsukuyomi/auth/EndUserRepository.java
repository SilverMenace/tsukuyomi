package dev.tsukuyomi.auth;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import dev.tsukuyomi.tenancy.ProjectRef;

import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

/**
 * SQL for end users. Runs on the owner connection: creating a user touches
 * both the project's "users" table and the platform's credential table, and
 * no tenant role may see credentials.
 */
@Repository
class EndUserRepository {

	record Credentials(UUID userId, String email, String passwordHash) {
	}

	public record EndUser(UUID id, String email, Instant createdAt) {
	}

	private final JdbcTemplate jdbc;

	EndUserRepository(JdbcTemplate jdbc) {
		this.jdbc = jdbc;
	}

	int count(UUID projectId) {
		return jdbc.queryForObject("select count(*) from tsk_platform.end_user where project_id = ?", Integer.class,
				projectId);
	}

	/** @return the new user's id, or empty if the email is taken in this project */
	Optional<UUID> insert(ProjectRef project, String email, String passwordHash) {
		try {
			// The profile row first: its id is generated by the project's table.
			UUID id = jdbc.queryForObject(
					"insert into \"" + project.schemaName() + "\".\"users\" (\"email\") values (?) returning \"id\"",
					UUID.class, email);
			jdbc.update("insert into tsk_platform.end_user (project_id, user_id, email, password_hash) values (?, ?, ?, ?)",
					project.id(), id, email, passwordHash);
			return Optional.of(id);
		}
		catch (DuplicateKeyException e) {
			return Optional.empty();
		}
	}

	Optional<Credentials> findByEmail(UUID projectId, String email) {
		return jdbc.query("select user_id, email, password_hash from tsk_platform.end_user where project_id = ? and email = ?",
				(rs, n) -> new Credentials(rs.getObject("user_id", UUID.class), rs.getString("email"),
						rs.getString("password_hash")),
				projectId, email)
			.stream()
			.findFirst();
	}

	Optional<EndUser> findById(UUID projectId, UUID userId) {
		return jdbc.query("select user_id, email, created_at from tsk_platform.end_user where project_id = ? and user_id = ?",
				(rs, n) -> new EndUser(rs.getObject("user_id", UUID.class), rs.getString("email"),
						rs.getTimestamp("created_at").toInstant()),
				projectId, userId)
			.stream()
			.findFirst();
	}

	List<EndUser> list(UUID projectId, int limit) {
		return jdbc.query("""
				select user_id, email, created_at from tsk_platform.end_user
				where project_id = ? order by created_at desc limit ?""",
				(rs, n) -> new EndUser(rs.getObject("user_id", UUID.class), rs.getString("email"),
						rs.getTimestamp("created_at").toInstant()),
				projectId, limit);
	}

	void insertSession(String tokenHash, UUID projectId, UUID userId, Instant expiresAt) {
		jdbc.update("insert into tsk_platform.end_user_session (token_hash, project_id, user_id, expires_at) values (?, ?, ?, ?)",
				tokenHash, projectId, userId, Timestamp.from(expiresAt));
	}

	/**
	 * Deletes the session and returns whose it was, in one statement, so a
	 * refresh token can be used exactly once even if two requests race.
	 */
	Optional<UUID> consumeSession(String tokenHash, UUID projectId) {
		return jdbc.query("""
				delete from tsk_platform.end_user_session
				where token_hash = ? and project_id = ? and expires_at > now() returning user_id""",
				(rs, n) -> rs.getObject("user_id", UUID.class), tokenHash, projectId)
			.stream()
			.findFirst();
	}

	void deleteExpiredSessions(UUID projectId) {
		jdbc.update("delete from tsk_platform.end_user_session where project_id = ? and expires_at <= now()", projectId);
	}

}
